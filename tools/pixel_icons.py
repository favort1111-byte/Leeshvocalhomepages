def svg(name):
    rows = ICONS[name]; out = []
    for y, row in enumerate(rows):
        assert len(row) == 16, (name, y, len(row))
        for x, c in enumerate(row):
            if c != ".": out.append(f'<rect x="{x}" y="{y}" width="1" height="1" fill="{PAL[c]}"/>')
    return '<svg viewBox="0 0 16 16" shape-rendering="crispEdges" aria-hidden="true">' + "".join(out) + "</svg>"
